export function detectLang() {
  try {
    const saved = localStorage.getItem('utsurikomi.lang');
    if (saved === 'ja' || saved === 'en') return saved;
  } catch (_) { /* 保存できない環境でも動かす */ }
  return (navigator.language || 'en').toLowerCase().startsWith('ja') ? 'ja' : 'en';
}

export function makeT(getLang) {
  return (key) => STRINGS[getLang()][key] ?? STRINGS.en[key] ?? key;
}
